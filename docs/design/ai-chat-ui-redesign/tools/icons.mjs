export function svg(name, cls) {
  const body = ICONS[name];
  if (!body) throw new Error('未定义的图标名: ' + name);
  const clsAttr = cls ? ' class="' + cls + '"' : '';
  return '<svg' + clsAttr + ' viewBox="0 0 24 24" fill="none" stroke="currentColor" ' +
    'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">' + body + '</svg>';
}

/** 把 <i class="..." data-icon="name"></i> 占位替换为内联 SVG */
export function inlineIcons(html) {
  const out = html.replace(/<i([^>]*?)data-icon="([^"]+)"([^>]*?)><\/i>/g, (_m, pre, name, post) => {
    const clsMatch = (pre + post).match(/class="([^"]*)"/);
    return svg(name, clsMatch ? clsMatch[1] : '');
  });
  const leftover = out.match(/data-icon=/g);
  if (leftover) throw new Error('仍有未替换的图标占位: ' + leftover.length);
  return out;
}

/** 生成一个可点击的图标元素（供生成器拼接 DOM 用） */
export function icon(name, cls) {
  return '<i' + (cls ? ' class="' + cls + '"' : '') + ' data-icon="' + name + '"></i>';
}
